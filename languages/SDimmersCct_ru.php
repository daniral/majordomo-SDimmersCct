<?php
/**
 * ============================================================
 * Словарь команд для управления лампой SDimmersCct2
 * ============================================================
 *
 * $dictionary - массив, определяющий шаблоны для распознавания команд:
 *   - 'SDimmersCct2_PATTERN_BRIGHTNESS': ключевые слова для управления яркостью
 *   - 'SDimmersCct2_PATTERN_TEMPERATURE': ключевые слова для управления цветовой температурой
 *
 * Каждое значение — строка с ключевыми словами, разделёнными |
 * Для каждого ключа определяется константа с префиксом LANG_
 *   например, LANG_SDimmersCct2_PATTERN_BRIGHTNESS
 * Эти константы используются для распознавания текстовых или голосовых команд.
 */

$dictionary = array(

    // Распознавание команд, связанных с яркостью
    'SDimmersCct2_PATTERN_BRIGHTNESS' => 'ярк|ярч|яркость|светлее|приглуш|тусклее',

    // Распознавание команд, связанных с цветовой температурой
    'SDimmersCct2_PATTERN_TEMPERATURE' => 'температур|тепл|цвет|холодн|синее|желт|прохладн|нейтрал'

);

foreach ($dictionary as $k => $v) {
    if (!defined('LANG_' . $k)) {
        @define('LANG_' . $k, $v);
    }
}
