Уменьшить яркость на (array("value"=>1--100)). Без  параметров на 10.
*/
/**
 * Уменьшает яркость лампы.
 *  array("value"=>1--100)
 * 
 * Если передан массив с ключом `value`, яркость уменьшается на указанное значение (1–100).
 * Если параметр не передан, используется значение по умолчанию: 10.
 *
 * @param array{
 *     value?: int|null   // На сколько уменьшить яркость (1–100). По умолчанию 10.
 * } $params Ассоциативный массив параметров.
 *
 * @return void
 */
adjustProperty($this, 'level', $params['value'] ?? null, 'down');